#!/usr/bin/env python3
"""The catalog of Base's shared helpers, and the pull request warning for copies.

A shared helper is a public Base function whose doc comment holds a line
"Shared helper: `<one-line example>`". Its first doc line is its purpose, and
the example names its full path (`bilibi_ui::params::blank_to_none(...)`).

Usage:
  shared-helpers.py            write apps/base/HELPERS.md from the doc comments
  shared-helpers.py --check    fail when apps/base/HELPERS.md is out of date
  shared-helpers.py warn [--base REF]
      warn about each free function this change adds whose name is a shared
      helper's. It never fails. A line "<path>: keep: <reason>" under
      "## Shared helpers" in the pull request body (PR_BODY) marks the copy as
      deliberate. Compares HEAD with the merge base of REF (default:
      origin/main, else main).
"""
import argparse
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = ROOT / "apps" / "base"
CATALOG = BASE / "HELPERS.md"
MARKER = re.compile(r"^Shared helper:\s*`(.+)`\s*$")
FN = re.compile(r"^pub(?:\([\w:]+\))?\s+(?:const\s+)?(?:async\s+)?fn\s+(\w+)")
SKIPPED_DIRS = {"target", "examples", "fixtures", "generated"}


def crate_name(source):
    for parent in source.parents:
        manifest = parent / "Cargo.toml"
        if manifest.is_file():
            match = re.search(r'^name\s*=\s*"([^"]+)"', manifest.read_text(), re.M)
            if match:
                return match.group(1).replace("-", "_")
    return None


def helpers():
    found, errors = [], []
    for source in sorted(BASE.rglob("*.rs")):
        if SKIPPED_DIRS & set(source.relative_to(BASE).parts[:-1]):
            continue
        lines = source.read_text().splitlines()
        for number, line in enumerate(lines):
            match = FN.match(line)
            if not match:
                continue
            docs, start = [], number
            while start > 0 and re.match(r"^\s*(///|#\[)", lines[start - 1]):
                start -= 1
                text = lines[start].strip()
                if text.startswith("///"):
                    docs.insert(0, text[3:].strip())
            examples = [m.group(1) for m in map(MARKER.match, docs) if m]
            if not examples:
                continue
            name, where = match.group(1), f"{source.relative_to(ROOT)}:{number + 1}"
            crate = crate_name(source)
            path = re.search(r"\b([a-z_][\w]*(?:::[a-z_][\w]*)*::" + re.escape(name) + r")\b", examples[0])
            if not docs[0] or MARKER.match(docs[0]) or (len(docs) > 1 and docs[1]):
                errors.append(f"{where}: `{name}` needs a one-line purpose as its first doc paragraph")
            elif not path or not path.group(1).startswith(f"{crate}::"):
                errors.append(f"{where}: the Shared helper example must call `{crate}::...::{name}`")
            else:
                found.append({"name": name, "path": path.group(1), "purpose": docs[0],
                              "example": examples[0], "source": str(source.relative_to(ROOT))})
    if errors:
        sys.exit("shared-helpers:\n  " + "\n  ".join(errors))
    return sorted(found, key=lambda helper: helper["path"])


def render(found):
    out = [
        "# Shared helpers",
        "",
        "<!-- Generated by scripts/shared-helpers.py from the doc comments; do not edit. -->",
        "",
        "Before writing a small helper, use one of these. To add one, give a public Base function a one-line purpose and a `Shared helper:` example line in its doc comment, then run `python3 scripts/shared-helpers.py`.",
        "",
        "| Helper | Purpose | Example | Source |",
        "|---|---|---|---|",
    ]
    for helper in found:
        cell = lambda text: text.replace("|", "\\|")
        source = helper["source"].removeprefix("apps/base/")
        out.append(f"| `{helper['path']}` | {cell(helper['purpose'])} | `{cell(helper['example'])}` | [{source}]({source}) |")
    return "\n".join(out) + "\n"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def resolve_base(requested):
    for ref in [requested] if requested else ["origin/main", "main"]:
        try:
            return git("merge-base", ref, "HEAD").strip()
        except subprocess.CalledProcessError:
            continue
    sys.exit("shared-helpers: no base ref found; fetch full history or pass --base")


def existed(base, path, name):
    try:
        before = git("show", f"{base}:{path}")
    except subprocess.CalledProcessError:
        return False
    return re.search(r"\bfn\s+" + re.escape(name) + r"\b", before) is not None


def added_functions(base):
    """Free functions (unindented) this change adds; a signature edit is not an addition."""
    path, line = None, 0
    for text in git("diff", "-U0", "--no-color", base, "HEAD", "--", "*.rs").splitlines():
        if text.startswith("+++ "):
            path = text[6:] if text.startswith("+++ b/") else None
        elif text.startswith("@@"):
            line = int(re.search(r"\+(\d+)", text).group(1))
        elif text.startswith("+") and path:
            match = re.match(r"^(?:pub(?:\([\w:]+\))?\s+)?(?:const\s+)?(?:async\s+)?fn\s+(\w+)", text[1:])
            if match and not existed(base, path, match.group(1)):
                yield path, line, match.group(1)
            line += 1


def warn(base_ref):
    by_name = {}
    for helper in helpers():
        by_name.setdefault(helper["name"], []).append(helper)
    body = os.environ.get("PR_BODY") or ""
    match = re.search(r"^##\s+Shared helpers\s*$(.*?)(?=^##\s|\Z)", body.replace("\r", ""), re.S | re.M)
    section = match.group(1) if match else ""
    listed = kept = 0
    for path, line, name in added_functions(resolve_base(base_ref)):
        same = [h for h in by_name.get(name, []) if h["source"] != path]
        if not same:
            continue
        listed += 1
        use = " or ".join(f"`{h['path']}` ({h['purpose'].rstrip('.')})" for h in same)
        if any(path in text and re.search(r"\bkeep:\s*\S{3,}", text) for text in section.splitlines()):
            kept += 1
            print(f"::notice file={path},line={line}::fn {name} is kept beside the shared helper {use}.")
            continue
        print(
            f"::warning file={path},line={line}::fn {name} has the name of the shared helper {use}. "
            f"Use it, or say why this one stays under '## Shared helpers' in the pull request body: "
            f"'{path}: keep: <reason>'. Catalog: apps/base/HELPERS.md."
        )
    print(f"shared-helpers: {listed} added function(s) named like a shared helper, {kept} kept with a reason.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", nargs="?", choices=["warn"])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--base")
    args = parser.parse_args()
    if args.command == "warn":
        return warn(args.base)
    text = render(helpers())
    if args.check:
        if not CATALOG.is_file() or CATALOG.read_text() != text:
            sys.exit("shared-helpers: apps/base/HELPERS.md is out of date; run python3 scripts/shared-helpers.py")
        print("shared-helpers: apps/base/HELPERS.md is current")
    else:
        CATALOG.write_text(text)
        print(f"shared-helpers: wrote {CATALOG.relative_to(ROOT)} ({len(text.splitlines()) - 8} helpers)")


main()
