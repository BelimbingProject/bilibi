#!/usr/bin/env python3
"""The map of what each Base module is for, read from the module READMEs.

Every Base module (a folder under apps/base with a Cargo.toml) has a README.md
whose first line is its `# ` heading and which holds one line each of
"**Use it for:** ..." and "**Not for:** ...". This script turns them into one
table, apps/base/CAPABILITIES.md, so a feature is designed on what Base
already does.

Usage:
  base-capabilities.py          write apps/base/CAPABILITIES.md
  base-capabilities.py --check  fail when it is out of date or a README lacks a line
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = ROOT / "apps" / "base"
MAP = BASE / "CAPABILITIES.md"
USE = re.compile(r"^\*\*Use it for:\*\*\s*(\S.*)$", re.M)
NOT = re.compile(r"^\*\*Not for:\*\*\s*(\S.*)$", re.M)


def crate_name(manifest):
    match = re.search(r'^name\s*=\s*"([^"]+)"', manifest.read_text(), re.M)
    return match.group(1).replace("-", "_") if match else None


def modules():
    found, errors = [], []
    for folder in sorted(p for p in BASE.iterdir() if (p / "Cargo.toml").is_file()):
        readme = folder / "README.md"
        where = readme.relative_to(ROOT)
        if not readme.is_file():
            errors.append(f"{where}: missing; give it a `# ` heading, a '**Use it for:**' line and a '**Not for:**' line")
            continue
        text = readme.read_text()
        heading = text.split("\n", 1)[0]
        use, avoid = USE.search(text), NOT.search(text)
        if not heading.startswith("# "):
            errors.append(f"{where}: the first line must be its `# ` heading")
        elif not use or not avoid:
            errors.append(f"{where}: needs one '**Use it for:** ...' line and one '**Not for:** ...' line")
        else:
            found.append({"id": f"base/{folder.name}", "crate": crate_name(folder / "Cargo.toml"),
                          "title": heading[2:].strip(), "use": use.group(1).strip(),
                          "not": avoid.group(1).strip(), "readme": f"{folder.name}/README.md"})
    if errors:
        sys.exit("base-capabilities:\n  " + "\n  ".join(errors))
    return found


def render(found):
    cell = lambda text: text.replace("|", "\\|")
    out = [
        "# Base capabilities",
        "",
        "<!-- Generated by scripts/base-capabilities.py from each module README; do not edit. -->",
        "",
        "Before designing a feature, find what Base already does here and build on that module. A Domain or Extension that needs approvals, history, notifications, files, jobs, schedules, settings or time uses the module below, not a table or loop of its own. Small helpers are in [HELPERS.md](HELPERS.md).",
        "",
        "To change a row, edit the module README's **Use it for:** or **Not for:** line and run `python3 scripts/base-capabilities.py`.",
        "",
        "| Module | Use it for | Not for |",
        "|---|---|---|",
    ]
    for module in found:
        name = f"[`{module['id']}`]({module['readme']}) `{module['crate']}`<br>{cell(module['title'])}"
        out.append(f"| {name} | {cell(module['use'])} | {cell(module['not'])} |")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    text = render(modules())
    if parser.parse_args().check:
        if not MAP.is_file() or MAP.read_text() != text:
            sys.exit("base-capabilities: apps/base/CAPABILITIES.md is out of date; run python3 scripts/base-capabilities.py")
        print("base-capabilities: apps/base/CAPABILITIES.md is current")
    else:
        MAP.write_text(text)
        print(f"base-capabilities: wrote {MAP.relative_to(ROOT)} ({len(text.splitlines()) - 10} modules)")


main()
