-- Reference tasks: non-business rows with an owner and an optional team, so a
-- walkthrough can prove that Grid keeps a reader to the rows their reach
-- admits (#683) in lists, summaries, projections and search.
CREATE TABLE base_grid_ref_tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL REFERENCES tenants(id),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 160),
 owner_user_id bigint NOT NULL CHECK(owner_user_id > 0),
 team_id bigint CHECK(team_id IS NULL OR team_id > 0),
 hours integer NOT NULL DEFAULT 0 CHECK(hours >= 0),
 UNIQUE(tenant_id,id)
);
CREATE INDEX base_grid_ref_tasks_owner_idx ON base_grid_ref_tasks(tenant_id,owner_user_id);
